# Builds src/content/library-data.ts from the harvested PubMed metadata + entries.py
import json, re, sys
sys.path.insert(0, '.')
from entries import E, MANUAL
import importlib
ST = {}
for _i in range(1, 7):
    ST.update(importlib.import_module(f'stories{_i}').ST)
assert set(ST) == set(E), (set(E) ^ set(ST))

def slugify(t):
    s = re.sub(r'[^a-z0-9]+', '-', t.lower()).strip('-')
    if len(s) > 60: s = s[:60].rsplit('-', 1)[0]
    return s

def minutes_of(paras):
    return max(2, round(len(' '.join(paras).split()) / 130))
S = '/tmp/claude-0/-home-claude/bbd28d26-13fb-5ce6-bd5a-562c8f9e28ca/scratchpad'
pool = json.load(open(f'{S}/pool.json'))

def initials(a):
    return f"{a.get('last_name','')} {a.get('initials','')}".strip()

def org_of(aff):
    if not aff: return ''
    parts = [p.strip() for p in re.split(r',|;', aff)]
    bad = re.compile(r'^(Department|Division|Faculty|School|Centro|Institute of|Dentistry|Special Care|Life Course)\b', re.I)
    for p in parts:
        if re.search(r'Cochrane', p): return p
    for p in parts:
        if bad.match(p): continue
        if re.search(r'\b(University|Universidade|Università|Universit[eéä]\w*|Charit\w*|Trinity College|College London)\b', p, re.I): return re.sub(r'^The ', '', p)
    for p in parts:
        if not bad.match(p) and re.search(r'Institut|College|Hospital|Centre|Center|Academy', p, re.I): return p
    return parts[0]

def kind(types, journal):
    if 'Cochrane' in journal: return 'cochrane'
    t = ' '.join(types).lower()
    if 'meta-analysis' in t or 'systematic' in t: return 'systematic'
    return 'review'

out = []
for pmid, (cat, ru, fa, en) in E.items():
    if pmid in pool:
        x = pool[pmid]; ids = x['identifiers']
        j = x['journal']; jn = j.get('iso_abbreviation') or j.get('title')
        au = [initials(a) for a in x['authors']]
        aff = ((x['authors'][0].get('affiliations') or [''])[0]) if x['authors'] else ''
        rec = dict(title=x['title'].rstrip('.'), journal=jn, year=int(x['publication_date']['year']),
                   doi=ids.get('doi') or x.get('doi') or '', pmc=ids.get('pmc') or '', authors=au, org=org_of(aff),
                   types=x['article_types'], kw=list(x.get('mesh_terms') or [])[:12])
    else:
        t, jn, y, doi, pmc, au, org, types, kw = MANUAL[pmid]
        rec = dict(title=t.rstrip('.'), journal=jn, year=int(y), doi=doi, pmc=pmc, authors=au, org=org, types=types, kw=kw)
    rec['journal'] = rec['journal'].replace('The Cochrane database of systematic reviews', 'Cochrane Database Syst Rev')
    team = 'Cochrane' if 'Cochrane' in rec['journal'] else ''
    st = ST[pmid]
    slug = slugify(en[0])
    out.append(dict(id=pmid, slug=slug, minutes=max(minutes_of(st['ru'][1]), minutes_of(st['en'][1])), cat=cat, year=rec['year'], journal=rec['journal'], type=kind(rec['types'], rec['journal']),
        oa=bool(rec['pmc']), pmc=rec['pmc'], doi=rec['doi'], authors=rec['authors'], org=rec['org'], team=team,
        titleEn=rec['title'], kw=rec['kw'],
        ru=dict(title=ru[0], sum=ru[1], key=st['ru'][0], p=st['ru'][1]),
        fa=dict(title=fa[0], sum=fa[1], key=st['fa'][0], p=st['fa'][1]),
        en=dict(title=en[0], sum=en[1], key=st['en'][0], p=st['en'][1])))

out.sort(key=lambda r: (-r['year'], r['id']))
ts = "// Generated by scripts/library/build.py from PubMed records. Do not edit by hand.\nimport type { LibEntry } from './library-ui';\n\nexport const library: LibEntry[] = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n"
open('../../src/content/library-data.ts', 'w').write(ts)
from collections import Counter
print(len(out), Counter(r['cat'] for r in out), Counter(r['type'] for r in out), 'oa', sum(r['oa'] for r in out))
slugs = [r['slug'] for r in out]
assert len(set(slugs)) == len(slugs), 'duplicate slug'
print('minutes:', Counter(r['minutes'] for r in out))
print('no doi:', [r['id'] for r in out if not r['doi']])
print('orgs:', [(r['id'], r['org'][:50]) for r in out][:60])
